"""Blender adapter — scene building, cameras, lighting, render.

Blender is usually absent on a workstation that only does drawing work, so the
adapter is split in two:

* the **builder script** is always produced — a standalone `build_scene.py` that
  reads the canonical snapshot and constructs an editable scene with real
  materials, cameras and lighting. It is a deliverable in its own right.
* **execution** happens only when a Blender executable is found, in headless
  mode (`blender -b -P`). When it is not found the adapter reports degraded
  output honestly and points at the OBJ fallback.

The scene is built from canonical geometry, so dimensions stay authoritative.
Renders derived from it are presentation material and are labelled as such.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from ..model import Project
from .base import Adapter, AdapterResult, Capability

SEARCH_PATHS = [
    r"C:\Program Files\Blender Foundation",
    r"C:\Program Files (x86)\Blender Foundation",
    "/Applications/Blender.app/Contents/MacOS",
    "/usr/bin",
    "/usr/local/bin",
    "/opt/blender",
]

BUILD_SCENE_TEMPLATE = r'''# -*- coding: utf-8 -*-
"""Auto-generated by OmniArchitect — editable scene builder.

Run:  blender -b -P build_scene.py -- --project snapshot.json --out ./out
Reads the canonical spatial model and builds walls, floors, ceilings, glazing,
furniture, materials, cameras and lighting. Units are metres (mm / 1000).
"""
import json
import math
import sys
from pathlib import Path

import bpy
import mathutils

ARGS = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def arg(name, default=None):
    if name in ARGS:
        return ARGS[ARGS.index(name) + 1]
    return default


PROJECT_JSON = Path(arg("--project", "snapshot.json"))
OUT_DIR = Path(arg("--out", "./out"))
RENDER = "--render" in ARGS
MM = 0.001


def clear():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def material(name, color, rough=0.6, metal=0.0, alpha=1.0, emit=None):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    bsdf = m.node_tree.nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Roughness"].default_value = rough
    bsdf.inputs["Metallic"].default_value = metal
    if "Alpha" in bsdf.inputs:
        bsdf.inputs["Alpha"].default_value = alpha
    if alpha < 1.0:
        m.blend_method = "BLEND"
    if emit is not None and "Emission Color" in bsdf.inputs:
        bsdf.inputs["Emission Color"].default_value = (*emit, 1.0)
        bsdf.inputs["Emission Strength"].default_value = 1.5
    return m


PALETTE = {
    "wall_structural": ((0.82, 0.80, 0.76), 0.85, None),
    "wall_partition": ((0.90, 0.89, 0.87), 0.85, None),
    "wall_uncertain": ((0.85, 0.45, 0.35), 0.85, None),
    "floor": ((0.72, 0.70, 0.66), 0.45, None),
    "ceiling": ((0.95, 0.95, 0.94), 0.9, (0.05, 0.05, 0.05)),
    "glass": ((0.60, 0.78, 0.85), 0.05, None),
    "door": ((0.55, 0.42, 0.30), 0.55, None),
    "furniture_soft": ((0.55, 0.56, 0.58), 0.85, None),
    "furniture_wood": ((0.62, 0.48, 0.34), 0.6, None),
    "furniture_white": ((0.92, 0.92, 0.91), 0.5, None),
}


def box(name, poly_mm, z0_mm, z1_mm, mat):
    """Extrude a 2D polygon (mm) into a mesh between two heights (mm)."""
    verts = [(*p, z0_mm * MM) for p in poly_mm] + [(*p, z1_mm * MM) for p in poly_mm]
    n = len(poly_mm)
    faces = [list(reversed(range(n))), list(range(n, 2 * n))]
    for i in range(n):
        j = (i + 1) % n
        faces.append([i, j, j + n, i + n])
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.validate()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    obj.data.materials.append(mat)
    return obj


def main():
    data = json.loads(PROJECT_JSON.read_text(encoding="utf-8"))
    clear()
    mats = {k: material(k, *v) for k, v in PALETTE.items()}

    levels = {l["id"]: l for l in data["levels"]}
    lid = arg("--level", data["levels"][0]["id"] if data["levels"] else "L1")
    wall_h = levels.get(lid, {}).get("height_mm", 2800.0)

    spaces = [s for s in data["spaces"] if s["level_id"] == lid and s.get("use") != "envelope"]
    for s in spaces:
        box(f"FLOOR_{s['id']}", s["boundary_mm2d"], -120, 0, mats["floor"])
        box(f"CEIL_{s['id']}", s["boundary_mm2d"], wall_h, wall_h + 120, mats["ceiling"])

    walls = [e for e in data["elements"] if e["type"] == "wall" and e["level_id"] == lid]
    openings = {}
    for e in data["elements"]:
        if e["type"] in ("door", "window") and e["level_id"] == lid:
            openings.setdefault(e["geometry"].get("host_wall"), []).append(e)

    def spans(length, holes):
        cuts = sorted((max(0.0, h["geometry"]["offset_mm"]),
                       min(length, h["geometry"]["offset_mm"] + h["geometry"]["width_mm"]))
                      for h in holes)
        merged = []
        for a, b in cuts:
            if merged and a <= merged[-1][1] + 1:
                merged[-1] = (merged[-1][0], max(merged[-1][1], b))
            else:
                merged.append((a, b))
        out, cur = [], 0.0
        for a, b in merged:
            if a - cur > 1:
                out.append((cur, a))
            cur = max(cur, b)
        if length - cur > 1:
            out.append((cur, length))
        return out

    def wall_poly(w, a, b, th):
        (x1, y1), (x2, y2) = w["geometry"]["start"], w["geometry"]["end"]
        dx, dy = x2 - x1, y2 - y1
        L = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / L * th / 2, dx / L * th / 2
        p1 = (x1 + dx * a / L, y1 + dy * a / L)
        p2 = (x1 + dx * b / L, y1 + dy * b / L)
        return [(p1[0] + nx, p1[1] + ny), (p2[0] + nx, p2[1] + ny),
                (p2[0] - nx, p2[1] - ny), (p1[0] - nx, p1[1] - ny)]

    for w in walls:
        key = "wall_uncertain" if w.get("uncertain") else (
            "wall_structural" if w["geometry"].get("kind") != "partition" else "wall_partition")
        th = w["geometry"].get("thickness_mm", 200)
        L = math.dist(w["geometry"]["start"], w["geometry"]["end"])
        holes = openings.get(w["id"], [])
        for i, (a, b) in enumerate(spans(L, holes)):
            poly = wall_poly(w, a, b, th)
            box(f"{w['id']}_SEG{i}", poly, 0, wall_h, mats[key])
        for h in holes:
            g = h["geometry"]
            poly = wall_poly(w, g["offset_mm"], g["offset_mm"] + g["width_mm"], th)
            if g["height_mm"] < wall_h:
                box(f"{h['id']}_LINTEL", poly, g["height_mm"], wall_h,
                    mats["wall_structural" if not w.get("uncertain") else "wall_uncertain"])

    for e in data["elements"]:
        if e["level_id"] != lid:
            continue
        if e["type"] == "window":
            g = e["geometry"]
            w = next((w for w in walls if w["id"] == g["host_wall"]), None)
            if not w:
                continue
            poly = wall_poly(w, g["offset_mm"], g["offset_mm"] + g["width_mm"], 40)
            box(f"{e['id']}_PANE", poly, g.get("sill_mm", 900),
                g.get("sill_mm", 900) + g["height_mm"], mats["glass"])
        elif e["type"] == "furniture":
            g = e["geometry"]
            cx, cy = g["center"]
            sw, sd, sh = g["size_mm"]
            r = math.radians(g.get("rotation_deg", 0))
            hw, hd = sw / 2, sd / 2
            poly = [(cx + x * math.cos(r) - y * math.sin(r),
                     cy + x * math.sin(r) + y * math.cos(r))
                    for x, y in ((-hw, -hd), (hw, -hd), (hw, hd), (-hw, hd))]
            cat = g.get("category", "")
            key = ("furniture_wood" if cat in
                   {"wardrobe", "tv_unit", "desk", "dining_table", "sideboard",
                    "bookshelf", "shelf_unit", "shoe_cabinet", "nightstand"}
                   else "furniture_soft" if cat in {"sofa", "bed_king", "bed_queen", "coffee_table"}
                   else "furniture_white")
            box(e["id"], poly, 0, sh, mats[key])

    # --- site: ground plane + daylight ------------------------------------
    bpy.ops.mesh.primitive_plane_add(size=200, location=(0, 0, -0.13))
    bpy.context.object.data.materials.append(material("ground", (0.35, 0.35, 0.34), 0.9))

    sun_data = bpy.data.lights.new("SUN", type="SUN")
    sun_data.energy = 3.0
    sun_data.angle = math.radians(3)
    sun = bpy.data.objects.new("SUN", sun_data)
    sun.rotation_euler = (math.radians(52), 0, math.radians(-135))
    bpy.context.collection.objects.link(sun)

    world = bpy.data.worlds.new("World")
    bpy.context.scene.world = world
    world.use_nodes = True
    world.node_tree.nodes["Background"].inputs[0].default_value = (0.55, 0.62, 0.72, 1)
    world.node_tree.nodes["Background"].inputs[1].default_value = 1.2

    # --- cameras: one per viewpoint, framed on the model bbox --------------
    pts = [p for s in spaces for p in s["boundary_mm2d"]]
    if pts:
        xs = [p[0] * MM for p in pts]
        ys = [p[1] * MM for p in pts]
        cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
        span = max(max(xs) - min(xs), max(ys) - min(ys))
        views = {
            "01_overview": (cx, cy - span * 1.1, wall_h * MM * 1.6),
            "02_living": (cx - span * 0.3, cy - span * 0.65, 1.55),
            "03_dining": (cx + span * 0.2, cy - span * 0.5, 1.55),
            "04_bedroom": (cx - span * 0.35, cy + span * 0.55, 1.55),
            "05_plan_axon": (cx, cy - span * 1.4, span * 1.2),
        }
        for name, loc in views.items():
            cam_data = bpy.data.cameras.new(name)
            cam_data.lens = 24 if name == "01_overview" else 35
            cam = bpy.data.objects.new(name, cam_data)
            cam.location = loc
            direction = mathutils.Vector((cx, cy, 1.2)) - mathutils.Vector(loc)
            cam.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()
            bpy.context.collection.objects.link(cam)
            bpy.context.scene.camera = cam
            if RENDER:
                bpy.context.scene.render.engine = "CYCLES"
                bpy.context.scene.cycles.samples = 64
                bpy.context.scene.render.resolution_x = 1600
                bpy.context.scene.render.resolution_y = 1000
                bpy.context.scene.render.filepath = str(OUT_DIR / f"{name}.png")
                bpy.ops.render.render(write_still=True)

    bpy.ops.wm.save_as_mainfile(filepath=str(OUT_DIR / "scene.blend"))
    print("OMNIARCHITECT_BUILD_OK objects=%d" % len(bpy.context.scene.objects))


main()
'''


class BlenderAdapter(Adapter):
    name = "blender"
    tool = "Blender"

    def preflight(self) -> Capability:
        exe = self.which("blender", "blender.exe")
        if not exe:
            exe = self._scan_common_paths()
        if exe:
            return Capability(
                name=self.name,
                available=True,
                executable=str(exe),
                version=self._version(exe),
                operations=["build_scene", "render_views", "export_glb"],
                notes=[],
            )
        return Capability(
            name=self.name,
            available=False,
            executable="",
            operations=[],
            notes=[
                "Blender not found on PATH or in the usual install locations",
                "scene builder script is still produced and runs on any host with Blender",
            ],
            degraded_to="OBJ/MTL mesh (adapters/mesh.py) + build_scene.py",
        )

    @staticmethod
    def _scan_common_paths() -> Optional[Path]:
        for root in SEARCH_PATHS:
            rp = Path(root)
            if not rp.exists():
                continue
            for candidate in list(rp.glob("*/blender.exe")) + list(rp.glob("blender")):
                if candidate.is_file():
                    return candidate
        return None

    @staticmethod
    def _version(exe) -> str:
        import subprocess

        try:
            out = subprocess.run([str(exe), "--version"], capture_output=True, text=True, timeout=30)
            return (out.stdout.splitlines() or ["unknown"])[0].strip()
        except Exception:
            return "unknown"

    # ------------------------------------------------------------------
    def write_snapshot(self, project: Project, path: str | Path) -> Path:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(
            json.dumps(project.to_dict(), ensure_ascii=False, indent=2), encoding="utf-8"
        )
        return p

    def build_scene_script(self, out_path: str | Path) -> Path:
        p = Path(out_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(BUILD_SCENE_TEMPLATE, encoding="utf-8")
        return p

    def build(
        self,
        project: Project,
        out_dir: str | Path,
        level_id: Optional[str] = None,
        render: bool = False,
    ) -> AdapterResult:
        out = Path(out_dir)
        out.mkdir(parents=True, exist_ok=True)
        snapshot = self.write_snapshot(project, out / "snapshot.json")
        script = self.build_scene_script(out / "build_scene.py")

        cap = self.preflight()
        res = AdapterResult(adapter=self.name, ok=True, revision=project.revision)
        res.artifacts.extend([str(snapshot), str(script)])
        res.validation["capability"] = cap.to_dict()

        if not cap.available:
            res.ok = True
            res.authoritative = True
            res.log.append(
                "Blender absent: produced snapshot.json + build_scene.py (runnable elsewhere). "
                "Use the mesh adapter for an immediately usable OBJ."
            )
            res.validation["degraded"] = True
            res.validation["degraded_to"] = cap.degraded_to
            return res

        import subprocess

        cmd = [cap.executable, "-b", "-P", str(script), "--",
               "--project", str(snapshot), "--out", str(out)]
        if render:
            cmd.append("--render")
        if level_id:
            cmd.extend(["--level", level_id])
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=3600)
        res.log.append(" ".join(cmd))
        res.ok = proc.returncode == 0 and "OMNIARCHITECT_BUILD_OK" in proc.stdout
        if proc.stdout:
            res.log.extend(proc.stdout.splitlines()[-30:])
        if not res.ok:
            res.errors.append(proc.stderr.strip()[-2000:] or f"exit {proc.returncode}")
        blend = out / "scene.blend"
        if blend.exists():
            res.artifacts.append(str(blend))
        if render:
            res.artifacts.extend(str(p) for p in sorted(out.glob("*.png")))
            res.authoritative = False  # renders are presentation, never dimensional
        return res
