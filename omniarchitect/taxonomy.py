@dataclass(frozen=True)
class SpecialQuestion:
    """行业专项问题。不是问卷，是"缺了这一条就做不下去"的那几条。"""

    qid: str
    slot: str
    text: str
    why: str = ""
    examples: Tuple[str, ...] = ()


@dataclass(frozen=True)
class Direction:
    """一条概念方向模板：组织逻辑先说清楚，再谈形式。"""

    name: str
    parti: str
    why: str


@dataclass(frozen=True)
class TypeSpec:
    code: str
    name: str
    discipline: str                       # architecture | interior | landscape
    family: str
    keywords: Tuple[str, ...]
    subtypes: Tuple[str, ...]
    focus: Tuple[str, ...]                # 这一类必须处理的专业要点
    directions: Tuple[Direction, ...]     # 2–3 条互不相同的组织逻辑
    s3_specific: Tuple[str, ...]          # 在专业通用任务之外，这一类特有的任务
    questions: Tuple[SpecialQuestion, ...] = ()
    capability: str = "concept_only"
    limitation: str = ""
    strategy_ids: Tuple[str, ...] = ()    # 已有推敲策略里可直接复用的（可空）
    #: 该类型是否已有成体系的推敲策略库（deliberation 里的 11 条）。
    #: 有就用老策略（它们是按这些类型写的）；没有才用本模块的方向模板。
    uses_profile_strategies: bool = False

    def to_dict(self) -> Dict[str, object]:
        return {
            "code": self.code,
            "name": self.name,
            "discipline": self.discipline,
            "family": self.family,
            "family_label": FAMILY_LABELS.get(self.family, self.family),
            "focus": list(self.focus),
            "directions": [d.name for d in self.directions],
            "s3_specific": list(self.s3_specific),
            "capability": self.capability,
            "capability_label": CAPABILITY_LABELS.get(self.capability, ""),
            "limitation": self.limitation,
            "subtype_count": len(self.subtypes),
        }


def _d(name: str, parti: str, why: str) -> Direction:
    return Direction(name=name, parti=parti, why=why)


def _q(qid: str, slot: str, text: str, why: str = "",
       examples: Tuple[str, ...] = ()) -> SpecialQuestion:
    return SpecialQuestion(qid=qid, slot=slot, text=text, why=why, examples=examples)


