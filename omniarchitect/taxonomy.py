def facilities(blob: str, primary: str) -> List[Dict[str, str]]:
    """主体类型下出现的配套功能（按词表，不猜）。"""
    out: List[Dict[str, str]] = []
    for label, terms, note in FACILITY_TERMS.get(primary, ()):
        hit = next((t for t in terms if t.lower() in blob.lower()), "")
        if not hit:
            continue
        out.append({"term": hit, "label": label, "note": note,
                    "primary": primary})
    return out


def facility_owners() -> Dict[str, Tuple[str, ...]]:
    """配套词 -> 它属于哪些主体类型。"""
    out: Dict[str, Tuple[str, ...]] = {}
    for code, rows in FACILITY_TERMS.items():
        for _label, terms, _note in rows:
            for t in terms:
                out.setdefault(t, ())
                if code not in out[t]:
                    out[t] = out[t] + (code,)
    return out


def _facility_only(term: str, code: str,
                   owners: Dict[str, Tuple[str, ...]]) -> bool:
    """这个命中词是否只是别的主体的配套（因此不能作为本类型的证据）。"""
    own = owners.get(term, ())
    return bool(own) and code not in own


def _is_facility_evidence(code: str, matched: Sequence[str],
                          anc: Sequence[Dict[str, str]], blob: str) -> bool:
    """某类型的命中是不是"只是在说主体项目里的配套"。"""
    if not matched or not anc:
        return False
    terms = {str(a["term"]).lower() for a in anc}
    # 命中词全部落在配套词里，才算"只是配套"
    if not all(any(t in m.lower() or m.lower() in t for t in terms) for m in matched):
        return False
    # 明确说要独立，就不降级
    return not any(w in blob for w in SEPARATE)


#: 明确排除 / 独占的表达：说了"只做"，其它专业就不自动进入范围。
EXCLUSIVE = ("只做", "只委托", "只需要", "仅做", "仅室内", "只负责", "不含")


def _blob(texts: Iterable[str]) -> str:
    return " ".join(str(t or "") for t in texts if t).strip()


def classify(texts: Sequence[str] | str, *, discipline: str = "",
             limit: int = 3) -> Classification:
    """从项目描述里识别用途（可多选）、性质与委托范围。

    只做「文字到标签」的映射，不做设计判断。名称与性质分开判：说「酒店」不等于
    说「新建酒店」，说「精装修」才是委托范围的证据。
    """
    blob = _blob([texts] if isinstance(texts, str) else texts)
    out = Classification()
    if not blob:
        out.note = "没有项目描述，无法识别类型"
        return out

    low = blob.lower()
    owners = facility_owners()
    # 客户说了"另建 / 独立 / 单独委托"，配套词就回到实质证据——这时它真是另一栋楼
    separate = any(w in blob for w in SEPARATE)
    hits: Dict[str, List[str]] = {}
    scores: Dict[str, float] = {}
    rank_scores: Dict[str, float] = {}
    substantive: Dict[str, float] = {}
    for code, spec in TYPES.items():
        matched = [k for k in spec.keywords if k.lower() in low]
        if not matched:
            continue
        # 配套词只算"很弱的证据"：它说明这个房间里可能有它，不说明项目是它。
        # 「酒店的会议中心」不该把 A2 办公抬成主体；「学校的食堂」不该带出 B5。
        strong = matched if separate else [
            k for k in matched if not _facility_only(k, code, owners)]
        weak = [k for k in matched if k not in strong]
        s = sum(_kw_score(k) for k in strong) + 0.25 * sum(
            _kw_score(k) for k in weak)
        # 排序用**永远**按配套折算的那一版：「另建独立体育馆」里，体育馆要留在
        # 用途清单里，但主体仍是学校——不能因为客户加建一栋就把学校改叫体育馆。
        pure = [k for k in matched if not _facility_only(k, code, owners)]
        s_rank = sum(_kw_score(k) for k in pure) + 0.25 * sum(
            _kw_score(k) for k in matched if k not in pure)
        if discipline and spec.discipline == discipline:
            s += 0.6
        for sub in spec.subtypes:
            if len(sub) >= 3 and sub in blob:
                out.subtype_hits[code] = sub
                s += 1.2
                break
        hits[code] = matched
        scores[code] = s
        rank_scores[code] = s_rank
        substantive[code] = sum(_kw_score(k) for k in strong)

    if not hits:
        out.note = "未命中已知类型：按最宽口径提问，不套任何专项"
        out.natures = natures(blob)
        out.commissions = commissions(blob)
        return out

    # 主体要看"实质证据"：只有配套词的编码（酒店里的会议中心）不该排在前面
    ranked = sorted(scores.items(),
                    key=lambda kv: (-rank_scores.get(kv[0], kv[1]), -kv[1], kv[0])
                    )[:max(1, limit)]
    # 明显弱于首项的命中不并列，避免「有酒店两个字就多一个类型」。
    # 下限取 1.0：单个两字关键词（酒店 / 医院 / 公园）本来只有 1.5 分，
    # 拿 2.0 当门槛会把整类项目判成「不认识」。
    top = ranked[0][1]
    kept = [c for c, s in ranked if s >= max(1.0, top * 0.45)]
    out.evidence = {c: hits[c][:6] for c in kept}

    # 「学校里的食堂」不是「餐饮工装」：只有配套证据的编码降级为附属功能，
    # 只有明确说要独立（另建 / 单独委托）才保留成第二用途。
    primary = kept[0] if kept else ""
    # 配套从**所有**主体类型取：综合体这类"容器型"主体自己不写配套表，
    # 它下面的商业/酒店才写——不然"综合体含影院餐饮"会静默丢掉两条。
    _seen: set = set()
    for code in kept:
        for a in facilities(blob, code):
            if a["label"] in _seen:
                continue
            _seen.add(a["label"])
            out.ancillary.append(a)
    if kept and not separate:
        rest = []
        counterpart = INTERIOR_COUNTERPART.get(primary, "")
        for code in kept:
            if code != primary and substantive.get(code, 0.0) <= 0.0:
                out.demoted.append(code)
                continue
            if code == counterpart:
                # 新建医院里的"医疗工装"是同一栋楼的室内专业，不是第二用途。
                # 委托范围仍由客户的话决定（说了精装修才进范围）。
                out.sibling.append({
                    "code": code, "name": TYPES[code].name, "discipline": "interior",
                    "note": "同一项目的室内专业，随委托范围决定是否展开",
                })
                continue
            rest.append(code)
        kept = rest

    out.codes = kept
    out.scores = {c: scores[c] for c in out.codes}
    out.evidence = {c: out.evidence.get(c, []) for c in out.codes}
    for c in out.demoted:
        out.evidence.setdefault(f"demoted:{c}", hits.get(c, [])[:4])
    out.natures = natures(blob)
    out.commissions = commissions(blob, codes=out.codes)
    if out.demoted:
        out.note = ("配套功能按主体项目处理，不单独形成委托："
                    + "、".join(a["label"] for a in out.ancillary))

    if out.subtype_hits and out.codes:
        out.confidence = "high"
    elif top >= 3.0:
        out.confidence = "medium"
    else:
        out.confidence = "low"
        out.note = "命中偏弱：先按宽口径提问，等客户确认具体类型"
    return out


def natures(text: str) -> List[str]:
    """项目性质，按证据强度排序。同一句里出现多个时全部保留。"""
    low = str(text or "").lower()
    found = [(k, sum(1 for c in cues if c in low))
             for k, cues in NATURE_CUES.items()]
    found = [(k, n) for k, n in found if n]
    found.sort(key=lambda kv: -kv[1])
    return [k for k, _ in found]


#: 明确说「整体做」的表达：三种专业同时进入范围。
WHOLE_PROJECT = ("整体委托", "全专业", "建筑+室内", "建筑、室内", "建筑室内景观",
                 "室内外一体", "交钥匙", "一体化设计", "建筑+景观")


def commissions(text: str, *, codes: Sequence[str] = ()) -> List[str]:
    """委托范围。

    两种证据并用，但都写进 evidence：文字里的动词性线索（"只做室内""精装"），
    以及已识别用途所属的专业（B 类必是室内、C 类必是景观）。**性质会否决用途**：
    既有酒店精装不因为它叫"酒店"就把建筑设计放进范围。
    """
    low = str(text or "").lower()
    if any(w in low for w in WHOLE_PROJECT):
        return ["architecture", "interior", "landscape"]
    got = [k for k, cues in COMMISSION_CUES.items()
           if any(c in low for c in cues)]
    exclusive = any(c in low for c in EXCLUSIVE)
    if exclusive and len(got) > 1:
        # "只做室内" 时，把由名称带出来的建筑/景观线索压掉
        for cue in ("室内", "精装", "软装", "硬装", "工装"):
            if cue in low:
                return ["interior"]
        for cue in ("庭院", "景观", "花园"):
            if cue in low:
                return ["landscape"]
    outs = list(got)
    nat = set(natures(low))
    # 既有空间装修 / 独立景观：不因为名字里带"酒店""住宅"就把建筑设计算进范围。
    # 这是本轮最要紧的一条——客户只买室内，不该收到一份建筑方案。
    block_arch = bool(nat & {"fitout", "landscape_only"}) and \
        not (nat & {"new_build", "extension"})
    for code in codes:
        spec = resolve(code)
        if not spec:
            continue
        if spec.discipline == "interior" and "interior" not in outs:
            outs.append("interior")
        elif spec.discipline == "landscape" and "landscape" not in outs:
            outs.append("landscape")
        elif spec.discipline == "architecture" and "architecture" not in outs:
            if block_arch and "architecture" not in got:
                continue
            outs.append("architecture")
    return [c for c in ("architecture", "interior", "landscape") if c in outs]


def resolve(code: str) -> Optional[TypeSpec]:
    return TYPES.get(str(code or "").strip().upper())


def by_discipline(discipline: str) -> List[TypeSpec]:
    return [t for t in TYPES.values() if t.discipline == discipline]


def index_rows() -> List[Tuple[str, str, str, str]]:
    """(编码, 名称, 专业, 子类数)。给文档与 CLI 用，避免文档手抄一遍。"""
    return [(t.code, t.name, t.discipline, str(len(t.subtypes)))
            for t in sorted(TYPES.values(), key=lambda x: (x.code[0], int(x.code[1:])))]


def s3_tasks(codes: Sequence[str], discipline: str) -> List[str]:
    """某专业的 S3 任务：通用项 + 本项目类型特有的项，去重后保序。"""
    base = list(S3_BASE.get(discipline, ()))
    for code in codes:
        spec = resolve(code)
        if not spec or spec.discipline != discipline:
            continue
        for item in spec.s3_specific:
            if item not in base:
                base.append(item)
    return base


def directions(codes: Sequence[str], discipline: str) -> List[Direction]:
    """该项目的概念方向模板。多用途时按编码顺序合并，去重。"""
    out: List[Direction] = []
    for code in codes:
        spec = resolve(code)
        if not spec or spec.discipline != discipline:
            continue
        for d in spec.directions:
            if d.name not in [x.name for x in out]:
                out.append(d)
    return out


def capability_of(codes: Sequence[str]) -> Dict[str, str]:
    """取最严格的那一档：一个项目里有医院，整体就不能声称 full。"""
    order = {"full": 0, "partial": 1, "concept_only": 2, "specialist": 3}
    best = "full"
    note = ""
    for code in codes:
        spec = resolve(code)
        if not spec:
            continue
        if order.get(spec.capability, 3) > order.get(best, 0):
            best = spec.capability
            note = spec.limitation
    return {"level": best, "label": CAPABILITY_LABELS.get(best, ""), "note": note}


def questions_for(codes: Sequence[str]) -> List[SpecialQuestion]:
    """该项目的行业专项问题（去重，保持类型顺序）。"""
    out: List[SpecialQuestion] = []
    seen: set = set()
    for code in codes:
        spec = resolve(code)
        if not spec:
            continue
        for q in spec.questions:
            if q.qid in seen:
                continue
            seen.add(q.qid)
            out.append(q)
    return out


def summary_lines(codes: Sequence[str]) -> List[str]:
    """一行一个类型的摘要，给报告与 CLI 复用。"""
    lines: List[str] = []
    for code in codes:
        spec = resolve(code)
        if not spec:
            continue
        lines.append(
            f"{spec.code} {spec.name}（{FAMILY_LABELS.get(spec.family, '')}）"
            f"：{CAPABILITY_LABELS.get(spec.capability, '')}")
    return lines


