#: 关键词权重：越长越具体，命中越可信。"医院"比"院"值钱。
def _kw_score(kw: str) -> float:
    return 1.0 + min(len(kw), 6) * 0.25


@dataclass
class Classification:
    """一次项目识别的结果。多用途、性质、委托范围各自独立。"""

    codes: List[str] = field(default_factory=list)
    natures: List[str] = field(default_factory=list)
    commissions: List[str] = field(default_factory=list)
    evidence: Dict[str, List[str]] = field(default_factory=dict)
    scores: Dict[str, float] = field(default_factory=dict)
    subtype_hits: Dict[str, str] = field(default_factory=dict)
    confidence: str = "low"            # low | medium | high
    note: str = ""
    #: 主体项目里的配套功能（食堂、体育馆、酒店餐厅…）。**不是**独立用途，
    #: 不进委托范围，但 S3 的任务书要把它们的房间算进去。
    ancillary: List[Dict[str, str]] = field(default_factory=list)
    #: 被降级掉的用途编码（原本命中、判定为配套），留作解释用
    demoted: List[str] = field(default_factory=list)
    #: 同一项目的另一专业（如新建医院的室内工装），不进用途清单、但可能有委托
    sibling: List[Dict[str, str]] = field(default_factory=list)

    @property
    def primary(self) -> str:
        return self.codes[0] if self.codes else ""

    def types(self) -> List[TypeSpec]:
        return [TYPES[c] for c in self.codes if c in TYPES]

    def disciplines(self) -> List[str]:
        return list(dict.fromkeys(t.discipline for t in self.types()))

    def to_dict(self) -> Dict[str, object]:
        return {
            "codes": list(self.codes),
            "primary": self.primary,
            "names": [TYPES[c].name for c in self.codes if c in TYPES],
            "families": [FAMILY_LABELS.get(TYPES[c].family, "") for c in self.codes
                         if c in TYPES],
            "natures": list(self.natures),
            "nature_labels": [NATURE_LABELS.get(n, n) for n in self.natures],
            "commissions": list(self.commissions),
            "commission_labels": [COMMISSION_LABELS.get(c, c) for c in self.commissions],
            "subtype_hits": dict(self.subtype_hits),
            "ancillary": [dict(a) for a in self.ancillary],
            "ancillary_labels": [a["label"] for a in self.ancillary],
            "demoted": list(self.demoted),
            "sibling": [dict(x) for x in self.sibling],
            "evidence": {k: v[:4] for k, v in self.evidence.items()},
            "scores": {k: round(v, 2) for k, v in self.scores.items()},
            "confidence": self.confidence,
            "note": self.note,
        }


