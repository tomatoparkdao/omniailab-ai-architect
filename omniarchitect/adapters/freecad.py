"""FreeCAD adapter — parametric solid modelling (phase two).

FreeCAD is not normally installed on a design workstation, so this adapter's
job today is to produce a script that, when run under FreeCADCmd, rebuilds the
canonical model as parametric solids. It is honest about not being able to run.

© OmniAiLab ｜ 开发者：Mochiball ｜ OmniAiLab AI建筑与室内设计总设计师（omniailabx.com）— 未经授权禁止复制、传播或二次分发。
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional

from ..model import Project
from .base import Adapter, AdapterResult, Capability

SCRIPT = r'''# -*- coding: utf-8 -*-
"""Auto-generated by OmniArchitect — FreeCAD parametric rebuild.

Run:  FreeCADCmd build_freecad.py --project snapshot.json --out model.FCStd
Every wall becomes a parametric Part::Box so the model stays editable.
"""
import json
import math
import sys
from pathlib import Path

import FreeCAD
import Part

ARGS = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def arg(name, default=None):
    return ARGS[ARGS.index(name) + 1] if name in ARGS else default


PROJECT = Path(arg("--project", "snapshot.json"))
OUT = Path(arg("--out", "model.FCStd"))
MM = 0.001

data = json.loads(PROJECT.read_text(encoding="utf-8"))
doc = FreeCAD.newDocument("OmniArchitect")

# datum grid
for i, lv in enumerate(data["levels"]):
    doc.addObject("App::Plane", f"LEVEL_{lv['id']}")

for w in [e for e in data["elements"] if e["type"] == "wall"]:
    g = w["geometry"]
    (x1, y1), (x2, y2) = g["start"], g["end"]
    th = g.get("thickness_mm", 200) * MM
    h = g.get("height_mm", 2800) * MM
    L = math.hypot(x2 - x1, y2 - y1) * MM
    box = doc.addObject("Part::Box", w["id"])
    box.Length, box.Width, box.Height = L, th, h
    box.Placement.Base = FreeCAD.Vector(x1 * MM, y1 * MM, 0)
    box.Placement.Rotation.Angle = math.atan2(y2 - y1, x2 - x1)

for e in data["elements"]:
    if e["type"] != "furniture":
        continue
    g = e["geometry"]
    sw, sd, sh = [v * MM for v in g["size_mm"]]
    box = doc.addObject("Part::Box", e["id"])
    box.Length, box.Width, box.Height = sw, sd, sh
    box.Placement.Base = FreeCAD.Vector(
        (g["center"][0] - g["size_mm"][0] / 2) * MM,
        (g["center"][1] - g["size_mm"][1] / 2) * MM, 0)
    box.Placement.Rotation.Angle = math.radians(g.get("rotation_deg", 0))

doc.recompute()
doc.saveAs(str(OUT))
print("OMNIARCHITECT_FREECAD_OK", len(doc.Objects))
'''


class FreeCadAdapter(Adapter):
    name = "freecad"
    tool = "FreeCAD"

    def preflight(self) -> Capability:
        exe = self.which("FreeCADCmd", "FreeCADCmd.exe", "freecadcmd", "freecad")
        if exe:
            return Capability(name=self.name, available=True, executable=str(exe),
                              operations=["rebuild_params", "export_step", "export_ifc"])
        return Capability(
            name=self.name,
            available=False,
            operations=[],
            notes=["FreeCAD/FreeCADCmd not found"],
            degraded_to="build_freecad.py script (runs on any host with FreeCAD)",
        )

    def export(self, project: Project, out_dir: str | Path, stem: str = "model") -> AdapterResult:
        out = Path(out_dir)
        out.mkdir(parents=True, exist_ok=True)
        snap = self.write_json(out / f"{stem}_snapshot.json", project.to_dict())
        script = out / "build_freecad.py"
        script.write_text(SCRIPT, encoding="utf-8")
        cap = self.preflight()
        res = AdapterResult(adapter=self.name, ok=True, revision=project.revision)
        res.artifacts.extend([str(snap), str(script)])
        res.validation["capability"] = cap.to_dict()
        if not cap.available:
            res.validation["degraded"] = True
            res.validation["degraded_to"] = cap.degraded_to
            res.log.append("FreeCAD absent — parametric rebuild script written for later execution")
            return res

        import subprocess

        proc = subprocess.run(
            [cap.executable, str(script), "--project", str(snap), "--out", str(out / f"{stem}.FCStd")],
            capture_output=True, text=True, timeout=1800,
        )
        res.ok = proc.returncode == 0
        res.log.append((proc.stdout or "").strip()[-400:])
        if not res.ok:
            res.errors.append((proc.stderr or "").strip()[-1500:])
        else:
            res.artifacts.append(str(out / f"{stem}.FCStd"))
        return res
