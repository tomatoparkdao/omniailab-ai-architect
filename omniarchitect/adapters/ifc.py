"""IFC / BIM adapter (IfcOpenShell).

Phase-two of the integration roadmap. When IfcOpenShell is importable the
adapter writes a real IFC4 file from the canonical model; when it is not, it
emits the generator script plus an IFC-ready JSON projection so the model data
is not lost while the toolchain is being installed.

© OmniAiLab ｜ 开发者：Mochiball ｜ OmniAiLab AI建筑与室内设计总设计师（omniailabx.com）— 未经授权禁止复制、传播或二次分发。
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from ..model import Project
from .base import Adapter, AdapterResult, Capability

GENERATOR = r'''# -*- coding: utf-8 -*-
"""Auto-generated by OmniArchitect — IFC4 export via IfcOpenShell.

Run:  python build_ifc.py --project snapshot.json --out model.ifc
"""
import argparse
import json
from pathlib import Path

import ifcopenshell
import ifcopenshell.api


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    data = json.loads(Path(args.project).read_text(encoding="utf-8"))
    model = ifcopenshell.file(schema="IFC4")
    project = ifcopenshell.api.run("root.create_entity", model, ifc_class="IfcProject",
                                   name=data.get("name") or data["project_id"])
    ifcopenshell.api.run("unit.assign_unit", model, length={"is_metric": True, "raw": "MILLIMETERS"})

    storeys = {}
    for lv in data["levels"]:
        st = ifcopenshell.api.run("root.create_entity", model, ifc_class="IfcBuildingStorey",
                                  name=lv.get("name") or lv["id"])
        st.Elevation = float(lv.get("elevation_mm", 0)) / 1000.0
        storeys[lv["id"]] = st

    for w in [e for e in data["elements"] if e["type"] == "wall"]:
        (x1, y1), (x2, y2) = w["geometry"]["start"], w["geometry"]["end"]
        th = float(w["geometry"].get("thickness_mm", 200))
        h = float(w["geometry"].get("height_mm", 2800))
        import math
        L = math.hypot(x2 - x1, y2 - y1)
        nx, ny = -(y2 - y1) / L * th / 2, (x2 - x1) / L * th / 2
        pts = [(x1 + nx, y1 + ny), (x2 + nx, y2 + ny), (x2 - nx, y2 - ny), (x1 - nx, y1 - ny)]
        wall = ifcopenshell.api.run("root.create_entity", model, ifc_class="IfcWallStandardCase",
                                    name=w["id"])
        ifcopenshell.api.run("spatial.assign_container", model, products=[wall],
                             relating_structure=storeys[w["level_id"]])
        # profile + extrusion are written explicitly so the geometry is inspectable
        profile = model.create_entity("IfcArbitraryClosedProfileDef", ProfileType="AREA",
                                      OuterCurve=model.create_entity(
                                          "IfcPolyline",
                                          Points=[model.create_entity("IfcCartesianPoint",
                                                                      Coordinates=(float(p[0]), float(p[1])))
                                                  for p in pts + [pts[0]]]))
        model.create_entity("IfcExtrudedAreaSolid", SweptArea=profile,
                            Position=model.create_entity("IfcAxis2Placement3D",
                                                         Location=model.create_entity(
                                                             "IfcCartesianPoint", Coordinates=(0., 0., 0.))),
                            ExtrudedDirection=model.create_entity("IfcDirection", DirectionRatios=(0., 0., 1.)),
                            Depth=float(h))

    model.write(args.out)
    print("OMNIARCHITECT_IFC_OK", len(list(model.by_type("IfcWallStandardCase"))))


main()
'''


class IfcAdapter(Adapter):
    name = "ifc"
    tool = "IfcOpenShell"

    def preflight(self) -> Capability:
        try:
            import ifcopenshell  # noqa: F401

            return Capability(
                name=self.name,
                available=True,
                version=getattr(ifcopenshell, "__version__", "unknown"),
                executable="python:ifcopenshell",
                operations=["write_ifc4", "read_back", "validate"],
            )
        except Exception:
            return Capability(
                name=self.name,
                available=False,
                operations=[],
                notes=[
                    "ifcopenshell is not installed in this interpreter",
                    "IFC projection JSON + generator script are still produced",
                ],
                degraded_to="ifc_projection.json + build_ifc.py",
            )

    def export(
        self,
        project: Project,
        out_dir: str | Path,
        stem: str = "model",
    ) -> AdapterResult:
        out = Path(out_dir)
        out.mkdir(parents=True, exist_ok=True)
        snap = self.write_json(out / f"{stem}_snapshot.json", project.to_dict())
        script = out / "build_ifc.py"
        script.write_text(GENERATOR, encoding="utf-8")

        res = AdapterResult(adapter=self.name, ok=True, revision=project.revision)
        res.artifacts.extend([str(snap), str(script)])
        cap = self.preflight()
        res.validation["capability"] = cap.to_dict()

        if not cap.available:
            proj = self._projection(project)
            p = self.write_json(out / f"{stem}_projection.json", proj)
            res.artifacts.append(str(p))
            res.validation["degraded"] = True
            res.validation["ifc_entities_planned"] = proj["counts"]
            res.log.append("ifcopenshell absent — wrote IFC projection + generator script")
            return res

        import subprocess, sys

        proc = subprocess.run(
            [sys.executable, str(script), "--project", str(snap), "--out", str(out / f"{stem}.ifc")],
            capture_output=True, text=True, timeout=1800,
        )
        res.ok = proc.returncode == 0 and "OMNIARCHITECT_IFC_OK" in proc.stdout
        res.log.append(proc.stdout.strip()[-500:] or "(no stdout)")
        if not res.ok:
            res.errors.append(proc.stderr.strip()[-1500:])
            return res
        res.artifacts.append(str(out / f"{stem}.ifc"))
        res.validation.update(self.read_back(out / f"{stem}.ifc"))
        return res

    # ------------------------------------------------------------------
    @staticmethod
    def _projection(project: Project) -> Dict[str, Any]:
        """IFC-ready projection: the exact entities that *will* be created."""
        walls = [e for e in project.by_type("wall")]
        spaces = [s for s in project.spaces if s.use != "envelope"]
        return {
            "schema": "IFC4",
            "project_id": project.project_id,
            "revision": project.revision,
            "counts": {
                "IfcProject": 1,
                "IfcBuildingStorey": len(project.levels),
                "IfcWallStandardCase": len(walls),
                "IfcSpace": len(spaces),
                "IfcDoor": len(project.by_type("door")),
                "IfcWindow": len(project.by_type("window")),
                "IfcFurnishingElement": len(project.by_type("furniture")),
            },
            "storeys": [
                {"id": l.id, "elevation_m": round(l.elevation_mm / 1000.0, 3), "name": l.name}
                for l in project.levels
            ],
            "spaces": [
                {"id": s.id, "name": s.name, "use": s.use, "area_m2": round(s.area_m2, 3)}
                for s in spaces
            ],
            "note": "Generated without ifcopenshell installed; run build_ifc.py once it is.",
        }

    def read_back(self, ifc_path: str | Path) -> Dict[str, Any]:
        p = Path(ifc_path)
        out: Dict[str, Any] = {"ok": False, "file": str(p), "errors": []}
        if not p.exists():
            out["errors"].append("file missing")
            return out
        try:
            import ifcopenshell

            model = ifcopenshell.open(str(p))
            counts = {t: len(model.by_type(t)) for t in
                      ("IfcProject", "IfcBuildingStorey", "IfcWallStandardCase", "IfcSpace")}
            out.update({"ok": counts.get("IfcWallStandardCase", 0) > 0, "counts": counts,
                        "size_bytes": p.stat().st_size})
            if not out["ok"]:
                out["errors"].append("no IfcWallStandardCase entities in output")
        except Exception as exc:
            out["errors"].append(str(exc))
        return out
